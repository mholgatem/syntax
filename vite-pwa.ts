import { readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';
import type { Plugin } from 'vite';
import { LANGUAGES } from './src/editor/languages';

// Makes the build an installable, offline-capable app (PWA) without extra dependencies:
//  - emits manifest.webmanifest, including file handlers so the installed app shows up in
//    the OS "Open with" menu for source files (Chrome / Edge);
//  - emits sw.js, a service worker that precaches every built file (Monaco included) so
//    the editor works offline. Navigations go to the network first, so a new deploy is
//    picked up on the next load; the page then offers to switch over (see src/pwa.ts).

const SW_SOURCE = (cacheName: string, assets: string[]) => `// Generated by vite-pwa.ts
const CACHE = ${JSON.stringify(cacheName)};
const ASSETS = ${JSON.stringify(assets)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(ASSETS)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k.startsWith('syntax-') && k !== CACHE).map((k) => caches.delete(k))),
    ),
  );
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req).catch(() =>
        caches.match(self.registration.scope, { ignoreSearch: true }).then((hit) => hit || Response.error()),
      ),
    );
    return;
  }
  event.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req)));
});
`;

function listFiles(dir: string, root = dir): string[] {
  let out: string[] = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out = out.concat(listFiles(full, root));
    else out.push(relative(root, full).split('\\').join('/'));
  }
  return out;
}

export function pwa(): Plugin {
  let base = '/';
  let publicDir = '';
  return {
    name: 'syntax-pwa',
    apply: 'build',
    configResolved(config) {
      base = config.base;
      publicDir = config.publicDir;
    },
    transformIndexHtml() {
      return [
        { tag: 'link', attrs: { rel: 'manifest', href: `${base}manifest.webmanifest` }, injectTo: 'head' },
        { tag: 'link', attrs: { rel: 'apple-touch-icon', href: `${base}icons/icon-192.png` }, injectTo: 'head' },
      ];
    },
    generateBundle(_options, bundle) {
      const extensions = [...new Set(LANGUAGES.flatMap((l) => l.extensions))].sort();
      const manifest = {
        name: 'Syntax',
        short_name: 'Syntax',
        description: 'A fast, private code editor with tabs, compare and highlighting for Verilog, SystemVerilog, VHDL and 60+ languages.',
        id: base,
        start_url: base,
        scope: base,
        display: 'standalone',
        display_override: ['window-controls-overlay', 'standalone'],
        background_color: '#1e1e1e',
        theme_color: '#1e6fd9',
        icons: [
          { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png' },
          { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png' },
          { src: 'icons/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
          { src: 'favicon.svg', sizes: 'any', type: 'image/svg+xml' },
        ],
        file_handlers: [{ action: base, accept: { 'text/plain': extensions } }],
        launch_handler: { client_mode: ['focus-existing', 'auto'] },
      };
      this.emitFile({ type: 'asset', fileName: 'manifest.webmanifest', source: JSON.stringify(manifest, null, 2) });

      const files = [...Object.keys(bundle), 'manifest.webmanifest', ...listFiles(publicDir)];
      const assets = ['./', ...[...new Set(files)].filter((f) => f !== 'sw.js' && f !== 'index.html').sort()];
      const hash = createHash('sha256').update(assets.join('\n'));
      for (const f of Object.values(bundle)) hash.update(f.type === 'chunk' ? f.code : typeof f.source === 'string' ? f.source : Buffer.from(f.source));
      const cacheName = `syntax-${hash.digest('hex').slice(0, 12)}`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: SW_SOURCE(cacheName, assets) });
    },
  };
}
